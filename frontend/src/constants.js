export const lookupLocationCoordinates = (city = '', description = '', province = 'PG') => {
    const cityNorm = (city || '').trim().toLowerCase();
    if (cityNorm && UMBRIA_TOWN_COORDINATES[cityNorm]) {
        return UMBRIA_TOWN_COORDINATES[cityNorm];
    }
    
    if (cityNorm) {
        for (const [key, coords] of Object.entries(UMBRIA_TOWN_COORDINATES)) {
            if (cityNorm.includes(key) || key.includes(cityNorm)) {
                return coords;
            }
        }
    }
    
    const descNorm = (description || '').toLowerCase();
    for (const [key, coords] of Object.entries(UMBRIA_TOWN_COORDINATES)) {
        if (descNorm.includes(key)) {
            return coords;
        }
    }
    
    if (province && province.toUpperCase() === 'TR') {
        return UMBRIA_TOWN_COORDINATES["terni"];
    }
    return UMBRIA_TOWN_COORDINATES["perugia"];
};